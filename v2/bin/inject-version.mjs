#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const rootPkgPath = resolve(here, "..", "..", "package.json");
const versionTsPath = resolve(here, "..", "src", "version.ts");
const { version } = JSON.parse(readFileSync(rootPkgPath, "utf8"));
const banner = "// Generated by v2/bin/inject-version.mjs. Do not edit.";
writeFileSync(versionTsPath, `${banner}\nexport const version = ${JSON.stringify(version)};\n`);
