#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { argv } from "node:process";

const here = dirname(fileURLToPath(import.meta.url));
const rootPkgPath = resolve(here, "..", "..", "package.json");
const v2PkgPath = resolve(here, "..", "package.json");
const versionTsPath = resolve(here, "..", "src", "version.ts");
const banner = "// Generated by v2/bin/inject-version.mjs. Do not edit.";

function parseVersionArg(argv) {
  const index = argv.indexOf("--version");
  if (index === -1) return null;
  const value = argv[index + 1];
  if (!value || value.startsWith("--")) {
    throw new Error("--version requires a value");
  }
  return value;
}

const explicit = parseVersionArg(argv.slice(2));

if (explicit) {
  writeFileSync(versionTsPath, `${banner}\nexport const version = ${JSON.stringify(explicit)};\n`);
  const v2Pkg = JSON.parse(readFileSync(v2PkgPath, "utf8"));
  v2Pkg.version = explicit;
  delete v2Pkg.private;
  writeFileSync(v2PkgPath, `${JSON.stringify(v2Pkg, null, 2)}\n`);
} else {
  // Prefer a real version injected into v2/package.json (release builds);
  // fall back to the root package.json for dev builds of the managed placeholder.
  const v2Version = JSON.parse(readFileSync(v2PkgPath, "utf8")).version;
  const version =
    v2Version && v2Version !== "0.0.0-managed"
      ? v2Version
      : JSON.parse(readFileSync(rootPkgPath, "utf8")).version;
  writeFileSync(versionTsPath, `${banner}\nexport const version = ${JSON.stringify(version)};\n`);
}
